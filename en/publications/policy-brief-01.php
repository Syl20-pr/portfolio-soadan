        <h2>2. From the Malabo Convention to the African Union AI Strategy</h2>
        <p>The adoption of the continental AI strategy by the African Union in 2024 marks a turning point. A political
          text without technical infrastructure, however, remains inoperative: regulators must be equipped with software
          inspection tools able to analyse the code, weights and telemetry of AI systems.</p>

