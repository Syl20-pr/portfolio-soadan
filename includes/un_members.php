    /**
     * Codes des États membres dont le drapeau SVG existe localement.
     * @return string[]
     */
    function un_member_codes_available(): array
    {
        static $ok = null;
        if ($ok === null) {
            $dir = ROOT_PATH . DIRECTORY_SEPARATOR . 'assets' . DIRECTORY_SEPARATOR . 'flags';
            $ok = [];
            foreach (glob($dir . DIRECTORY_SEPARATOR . '*.svg') ?: [] as $f) {
                $code = strtoupper(basename($f, '.svg'));
                if (preg_match('/^[A-Z]{2}$/', $code)) {
                    $ok[] = $code;
                }
            }
            sort($ok);
        }
        return $ok;
    }
